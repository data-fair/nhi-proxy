import { test } from 'node:test'
import assert from 'node:assert'
import { cp, mkdtemp, readFile, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import https from 'node:https'
import { spawnSync } from 'node:child_process'
import { generateCa, loadCa, certForHost, spkiPin } from './ca.ts'

const setup = async () => {
  const dir = await mkdtemp(join(tmpdir(), 'nhi-'))
  await generateCa(dir)
  return loadCa(dir)
}

test('a minted certificate is accepted by node TLS when the CA is trusted', async () => {
  const ca = await setup()
  const { cert, key } = certForHost(ca, 'site.example.com')
  const server = https.createServer({ cert, key }, (req, res) => res.end('ok'))
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve))
  const port = (server.address() as any).port
  const body = await new Promise<string>((resolve, reject) => {
    https.get({
      host: '127.0.0.1',
      port,
      path: '/',
      servername: 'site.example.com', // SNI, as the proxy sets it
      ca: ca.caCertPem // trust ONLY our CA
    }, res => {
      let b = ''
      res.on('data', c => { b += c })
      res.on('end', () => resolve(b))
    }).on('error', reject)
  })
  assert.equal(body, 'ok')
  server.close()
})

test('the SPKI pin is stable across hostnames', async () => {
  const ca = await setup()
  const a = certForHost(ca, 'a.example.com')
  const b = certForHost(ca, 'b.example.com')
  assert.notEqual(a.cert, b.cert, 'each host gets its own certificate')
  assert.equal(a.key, b.key, 'but they share one leaf keypair')
  assert.match(spkiPin(ca), /^[A-Za-z0-9+/]+=*$/)
})

test('certForHost is memoized', async () => {
  const ca = await setup()
  assert.equal(certForHost(ca, 'x.example.com').cert, certForHost(ca, 'x.example.com').cert)
})

// Python 3.13+ verifies with X509_STRICT by default, which demands the key
// identifier extensions; openssl's -x509_strict is the same check
const noOpenssl = spawnSync('openssl', ['version']).status !== 0
const strictVerify = async (caPem: string, leafPem: string, hostname: string) => {
  const dir = await mkdtemp(join(tmpdir(), 'nhi-verify-'))
  await writeFile(join(dir, 'ca.crt'), caPem)
  await writeFile(join(dir, 'leaf.crt'), leafPem)
  const r = spawnSync('openssl', ['verify', '-x509_strict', '-purpose', 'sslserver',
    '-verify_hostname', hostname, '-CAfile', join(dir, 'ca.crt'), join(dir, 'leaf.crt')], { encoding: 'utf8' })
  return r.stdout + r.stderr
}

test('a minted chain passes strict X.509 verification', { skip: noOpenssl && 'needs openssl' }, async () => {
  const ca = await setup()
  const { cert } = certForHost(ca, 'site.example.com')
  assert.match(await strictVerify(ca.caCertPem, cert, 'site.example.com'), /: OK/)
})

// test-fixtures/forge-ca was generated by 0.2.x (node-forge): its CA has no
// key identifiers, and tools already trust it by path or by the leaf pin
test('a CA from an earlier version is reissued in place, keeping its keys', { skip: noOpenssl && 'needs openssl' }, async () => {
  const dir = await mkdtemp(join(tmpdir(), 'nhi-'))
  await cp('test-fixtures/forge-ca', dir, { recursive: true })
  const caKeyBefore = await readFile(join(dir, 'ca.key'), 'utf8')

  const ca = await loadCa(dir)
  const { cert } = certForHost(ca, 'site.example.com')

  const caOnDisk = await readFile(join(dir, 'ca.crt'), 'utf8')
  assert.match(await strictVerify(caOnDisk, cert, 'site.example.com'), /: OK/)
  assert.equal(await readFile(join(dir, 'ca.key'), 'utf8'), caKeyBefore)
  assert.equal(spkiPin(ca), 'jGfxQVin2T49cDc+fS85OMDOJt/e+MKg7dbVfR4B5a4=', 'the browser pin survives')
})
